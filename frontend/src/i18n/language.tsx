export type TranslationKey = keyof typeof translations.en

export type Values = Record<string, string | number>

export type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, values?: Values) => string
  formatDateTime: (value: string) => string
  formatDate: (value: string) => string
  severityLabel: (value: Severity) => string
  statusLabel: (value: IncidentStatus) => string
  sourceLabel: (value: IncidentSource) => string
  feedbackLabel: (value: FeedbackRating) => string
}

export const LanguageContext = createContext<LanguageContextValue | null>(null)

export function interpolate(text: string, values?: Values) {
  if (!values) {
    return text
  }

  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    text,
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)

  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider')
  }

  return context
}
